"""Emit the system-prompt openings the Gemini proxy accepts, so only this game's requests pass.

Usage:
    python -m scripts.worker_fingerprints          # check workers/gemini-proxy/src/fingerprints.ts is current
    python -m scripts.worker_fingerprints --write  # regenerate it after prompt wording changes, then redeploy
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from host.free_actions import PLAN_PROMPT
from host.gm_contract import build_gm_contract_prompt

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "workers" / "gemini-proxy" / "src" / "fingerprints.ts"


def fingerprints() -> dict[str, str]:
    """First line of each system prompt the game sends; Gemini receives them joined, so the first one leads."""
    prompts = {
        "plan": PLAN_PROMPT,
        "gm": build_gm_contract_prompt(),
        "narration": build_gm_contract_prompt(narration_only=True),
    }
    return {name: prompt.split("\n", 1)[0] for name, prompt in prompts.items()}


def render() -> str:
    lines = [
        "// Generated by `python -m scripts.worker_fingerprints --write`; do not edit by hand.",
        "// systemInstruction must start with one of these, and a plan request must carry a JSON schema.",
        "export const FINGERPRINTS: Record<string, string> = {",
    ]
    lines += [f"\t{name}: {json.dumps(text, ensure_ascii=False)}," for name, text in fingerprints().items()]
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.write:
        TARGET.write_text(render(), encoding="utf-8")
        print(f"[fingerprints] wrote {TARGET}")
    elif TARGET.read_text(encoding="utf-8") != render():
        raise SystemExit("worker fingerprints are stale; run python -m scripts.worker_fingerprints --write and redeploy")
    else:
        print("[fingerprints] up to date")


if __name__ == "__main__":
    main()
